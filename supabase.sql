create table if not exists public.jarvis_devices (
  device_id text primary key,
  device_name text not null,
  device_type text not null default 'android',
  battery integer,
  charging boolean,
  metadata jsonb not null default '{}'::jsonb,
  last_seen timestamptz not null default now()
);

create table if not exists public.jarvis_location (
  id bigint generated by default as identity primary key,
  device_id text not null unique,
  latitude double precision not null,
  longitude double precision not null,
  accuracy double precision,
  altitude double precision,
  battery integer,
  updated_at timestamptz not null default now()
);

create table if not exists public.jarvis_sentinel_state (
  device_id text primary key,
  enabled boolean not null default false,
  mode text not null default 'motion',
  updated_at timestamptz not null default now()
);

create table if not exists public.jarvis_sentinel_events (
  id bigint generated by default as identity primary key,
  device_id text not null,
  event_type text not null,
  person_name text,
  confidence double precision,
  image_url text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_jarvis_sentinel_created_at on public.jarvis_sentinel_events(created_at desc);
create index if not exists idx_jarvis_sentinel_device on public.jarvis_sentinel_events(device_id);

create or replace function public.jarvis_touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists jarvis_location_touch on public.jarvis_location;
create trigger jarvis_location_touch before update on public.jarvis_location
for each row execute function public.jarvis_touch_updated_at();

drop trigger if exists jarvis_sentinel_state_touch on public.jarvis_sentinel_state;
create trigger jarvis_sentinel_state_touch before update on public.jarvis_sentinel_state
for each row execute function public.jarvis_touch_updated_at();

-- Backend uses service_role. Do not expose the service key to J4+/browser.
alter table public.jarvis_devices enable row level security;
alter table public.jarvis_location enable row level security;
alter table public.jarvis_sentinel_state enable row level security;
alter table public.jarvis_sentinel_events enable row level security;
